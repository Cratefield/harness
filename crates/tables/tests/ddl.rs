#[test]
fn sqlite_ddl_is_exactly_this() {
    let sql = schema(EVERYTHING).ddl(SqlDialect::Sqlite).expect("renders");
    assert_eq!(sql, SQLITE_EXPECTED);
}

#[test]
fn postgres_ddl_is_exactly_this() {
    let sql = schema(EVERYTHING)
        .ddl(SqlDialect::Postgres)
        .expect("renders");
    assert_eq!(sql, POSTGRES_EXPECTED);
}

#[test]
fn the_same_definition_always_renders_byte_identical_sql() {
    // Twice from one value, and once more from a second parse of the same
    // manifest, which is what would catch an iteration order that depends
    // on a hash map rather than on the declaration.
    for dialect in SqlDialect::ALL.iter().copied() {
        let once = schema(EVERYTHING).ddl(dialect).expect("renders");
        let twice = schema(EVERYTHING).ddl(dialect).expect("renders");
        let reparsed = schema(EVERYTHING).ddl(dialect).expect("renders");
        assert_eq!(once.as_bytes(), twice.as_bytes());
        assert_eq!(once.as_bytes(), reparsed.as_bytes());
    }
}

#[test]
fn the_manifests_section_order_does_not_reach_the_sql() {
    let declared = schema(EVERYTHING);
    let mut shuffled = declared.clone();
    shuffled.tables.reverse();
    // `Schema::new` is what a caller uses to build a schema by hand, and
    // it sorts, so a reversed input renders the same script.
    let sorted = Schema::new(shuffled.tables);
    assert_eq!(
        sorted.ddl(SqlDialect::Sqlite).expect("renders"),
        declared.ddl(SqlDialect::Sqlite).expect("renders")
    );
}

#[test]
fn both_dialects_pass_the_portable_sql_lint() {
    // The same predicate `fz doctor` runs over a module's migrations and
    // the Postgres runner uses to pick a migration set.
    for dialect in SqlDialect::ALL.iter().copied() {
        let sql = schema(EVERYTHING).ddl(dialect).expect("renders");
        let hits = cratefield_core::lint_portable_sql(&sql);
        assert!(hits.is_empty(), "{}: {hits:?}", dialect.name());
    }
}

#[test]
fn generated_ddl_only_creates() {
    for dialect in SqlDialect::ALL.iter().copied() {
        let sql = schema(EVERYTHING)
            .ddl(dialect)
            .expect("renders")
            .to_uppercase();
        assert!(!sql.contains("DROP "), "forward-only: no DROP");
        assert!(!sql.contains("ALTER "), "forward-only: no ALTER");
        assert!(!sql.contains("DELETE "), "forward-only: no DELETE");
    }
}

#[test]
fn an_invalid_definition_renders_no_sql() {
    let schema = schema(
        r#"
[tables.post]
[[tables.post.fields]]
name = "id"
kind = "uuid"
required = true
[[tables.post.fields]]
name = "order"
kind = "text"
"#,
    );
    let error = schema
        .ddl(SqlDialect::Sqlite)
        .expect_err("a reserved word must not reach SQL");
    assert!(
        error.problems.iter().any(|line| line.contains("reserved")),
        "{:#?}",
        error.problems
    );
}

#[test]
